"""Synthetic demo shop: a small Nepali kirana (grocery) shop, for development, tests and demos.

EVERYTHING here is made up. Product names are generic (no real brands), supplier
names end in "(demo)", and the sales are generated by the rules below, so the
demo never depends on M5 or any real shop's data. Amounts are in Nepalese rupees.

How daily demand is generated (seeded, so the same inputs give the same data):
  expected units = base rate x weekday effect x slow growth x festival lift
  - weekday: busier on Friday and Saturday (Saturday is the weekly holiday);
  - growth: +8% a year;
  - festivals: demand rises in the days before Dashain and Tihar, by a
    different amount per product (oil, sugar, chiura, candles and diyo rise most);
  - pattern: "smooth" and "erratic" items sell most days (Poisson or a more
    variable negative binomial); "intermittent" and "lumpy" items sell on few
    days, in small or large, variable quantities;
  - a few short out-of-stock spells per item (recorded as 0 units, not
    available), and one price rise for some items on 1 Magh (mid-January).
Festival dates are the real ones from ml/calendar/nepal_festivals.json; the shop is closed on Vijaya Dashami.
"""

