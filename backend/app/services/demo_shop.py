# Festivals come from the same calendar the forecasts use (ml/calendar/nepal_festivals.json), so the demo's
# festival peaks fall exactly where the model expects them: (festival, build-up start, main day, last day).
FESTIVALS = [(f.key, f.window[0], f.main, f.window[1]) for f in festivals() if f.key in ("dashain", "tihar")]
# Calendar rows: (day, event name, event type, shop open?). The shop closes on Vijaya Dashami.
EVENTS = sorted({(f.main, f.main_label, "Festival", f.key != "dashain") for f in festivals()}
                | {(f.start, "Ghatasthapana", "Festival", True) for f in festivals() if f.key == "dashain" and f.start}
                | {(f.end, "Bhai Tika", "Festival", True) for f in festivals() if f.key == "tihar" and f.end})
PRICE_RISE_DAYS = [date(2025, 1, 14), date(2026, 1, 15)]       # about 1 Magh each year
WEEKDAY_EFFECT = [1.0, 0.95, 0.95, 0.95, 1.0, 1.15, 1.25]      # Sunday .. Saturday
GROWTH_PER_YEAR = 0.08
STOCKOUT_SPELLS_PER_YEAR = 1.5
# Opening stock as days of cover: a mix of nearly empty, low, healthy and too much stock.
COVER_DAYS = [(0.25, (0, 2)), (0.10, (3, 6)), (0.50, (8, 30)), (0.15, (60, 120))]


@dataclass
class DemoShopData:
    start: date
    end: date                                    # last day with sales
    products: list[DemoProduct]
    sales: dict[str, list[tuple[date, int, float, bool]]]    # sku -> (day, units, price, available)
    last_price: dict[str, float]
    last_cost: dict[str, float]
    opening_stock: dict[str, int]
    calendar: list[dict] = field(default_factory=list)


def festival_intensity(day: date, festival: str) -> float:
    """0 outside the festival; rises to 1 on the main day, stays high to the last day."""
    for name, begin, main, last in FESTIVALS:
        if name != festival or not begin <= day <= last:
            continue
        if day >= main:
            return 1.0
        return (day - begin).days / max((main - begin).days, 1)
    return 0.0


def _sunday_index(day: date) -> int:
    return (day.weekday() + 1) % 7               # Python Monday = 0 -> Sunday = 0


def expected_units(product: DemoProduct, day: date, start: date) -> float:
    years = (day - start).days / 365
    lift = (1 + (product.dashain_lift - 1) * festival_intensity(day, "dashain")) \
        * (1 + (product.tihar_lift - 1) * festival_intensity(day, "tihar"))
    return product.base_daily * WEEKDAY_EFFECT[_sunday_index(day)] * (1 + GROWTH_PER_YEAR * years) * lift


def _draw(rng: np.random.Generator, pattern: str, mean: float) -> int:
    if pattern == "smooth":
        return int(rng.poisson(mean))
    if pattern == "erratic":
        k = 1.5                                       # smaller k = more variable
        return int(rng.negative_binomial(k, k / (k + mean)))
    size = 1.4 if pattern == "intermittent" else 4.0     # average units when it sells
    if rng.random() >= min(0.95, mean / size):
        return 0
    if pattern == "intermittent":
        return 1 + int(rng.poisson(size - 1))
    return 1 + int(rng.negative_binomial(1, 1 / size))


def _price_on(product: DemoProduct, day: date, start: date, base: float) -> float:
    """Price on `day`: the starting price raised once for every rise day since the history began."""
    rises = sum(start < d <= day for d in PRICE_RISE_DAYS)
    return round(base * (1 + product.price_rise) ** rises, 0 if base >= 50 else 1)


def generate(end: date, days: int = DEFAULT_HISTORY_DAYS, seed: int = DEMO_SEED) -> DemoShopData:
    """Sales from `end - days + 1` to `end`, opening stock as of the day after `end`."""
    rng = np.random.default_rng(seed)
    start = end - timedelta(days=days - 1)
    closed = {d for d, _, _, is_open in EVENTS if not is_open}
    all_days = [start + timedelta(days=k) for k in range(days)]
    # Prices given in the table are today's; earlier days are before the price rises.
    rises_in_history = {p.sku: sum(start < d <= end for d in PRICE_RISE_DAYS) for p in PRODUCTS}

    sales, last_price, last_cost, opening = {}, {}, {}, {}
    for product in PRODUCTS:
        factor = (1 + product.price_rise) ** rises_in_history[product.sku]
        base_price, base_cost = product.price / factor, product.cost / factor
        out_until = start - timedelta(days=1)
        rows = []
        for day in all_days:
            if day > out_until and rng.random() < STOCKOUT_SPELLS_PER_YEAR / 365:
                out_until = day + timedelta(days=int(rng.integers(1, 5)))
            available = day not in closed and day > out_until
            units = _draw(rng, product.pattern, expected_units(product, day, start)) if available else 0
            rows.append((day, units, _price_on(product, day, start, base_price), available))
        sales[product.sku] = rows
        last_price[product.sku] = rows[-1][2]
        last_cost[product.sku] = round(base_cost * (rows[-1][2] / base_price), 2)

        recent = np.mean([u for _, u, _, a in rows[-28:] if a] or [0])
        # Daily-delivery (fresh) items are never overstocked.
        bands = COVER_DAYS[:-1] if SUPPLIER_LEAD[product.supplier] <= 1 else COVER_DAYS
        weights = np.array([w for w, _ in bands])
        low, high = bands[rng.choice(len(bands), p=weights / weights.sum())][1]
        opening[product.sku] = int(round(recent * rng.uniform(low, high)))

    events = {d: (n, t, o) for d, n, t, o in EVENTS}
    calendar = []
    for k in range(days + CALENDAR_DAYS_AHEAD):
        day = start + timedelta(days=k)
        name, kind, is_open = events.get(day, (None, None, True))
        calendar.append({"day": day, "event_name": name, "event_type": kind, "is_store_open": is_open})
    return DemoShopData(start=start, end=end, products=list(PRODUCTS), sales=sales, last_price=last_price,
                        last_cost=last_cost, opening_stock=opening, calendar=calendar)


def money(value: float) -> Decimal:
    return Decimal(str(round(float(value), 2)))


# ---------------------------------------------------------------- loading into the database

OPENING_REASON = "Opening balance: DEMO synthetic stock"


def load(session: Session, data: DemoShopData, name: str = DEMO_SHOP_NAME) -> dict[str, int]:
    """Create a new demo shop (marked is_demo) holding `data`, and switch the session to it.

    Other shops are not touched, so several demo shops can exist (e.g. in tests). The caller commits.
    """
    shop = create_shop(session, name, is_demo=True)
    categories = {code: Category(code=code, name=name) for code, name in CATEGORIES.items()}
    suppliers = {code: Supplier(code=code, name=name, lead_time_days=lead, lead_time_sd_days=money(sd))
                 for code, name, lead, sd in SUPPLIERS}
    session.add_all([*categories.values(), *suppliers.values()])

    # Calendar days are shared facts: add the missing ones, never change existing rows.
    existing = set(session.scalars(select(CalendarDay.day).where(
        CalendarDay.day.between(data.calendar[0]["day"], data.calendar[-1]["day"]))))
    new_days = [row for row in data.calendar if row["day"] not in existing]
    if new_days:
        session.execute(insert(CalendarDay), new_days)

    products = {p.sku: Product(sku=p.sku, name=p.name, category=categories[p.category],
                               supplier=suppliers[p.supplier], unit_price=money(data.last_price[p.sku]),
                               unit_cost=money(data.last_cost[p.sku]), min_order_qty=p.min_order_qty,
                               pack_size=p.pack_size, demand_class=p.pattern)
                for p in data.products}
    session.add_all(products.values())
    session.flush()

    rows = [{"shop_id": shop.id, "product_id": products[sku].id, "sales_date": day, "units": units, "unit_price": money(price),
             "is_available": available}
            for sku, days in data.sales.items() for day, units, price, available in days]
    for start in range(0, len(rows), 20_000):
        session.execute(insert(DailySales), rows[start:start + 20_000])

    for sku, product in products.items():
        qty = data.opening_stock[sku]
        session.add(InventoryBalance(product_id=product.id, on_hand=qty, backorders=0))
        if qty > 0:
            session.add(InventoryTransaction(product_id=product.id, txn_type=TransactionType.INITIAL,
                                             quantity=qty, balance_after=qty, reason=OPENING_REASON))

    session.flush()
    return {"shop_id": shop.id, "categories": len(categories), "suppliers": len(suppliers), "products": len(products),
            "daily_sales": len(rows), "calendar_days_added": len(new_days),
            "products_with_stock": sum(q > 0 for q in data.opening_stock.values())}
